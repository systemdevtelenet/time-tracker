-- Target: CTNP Systems self-hosted PostgreSQL, not the separate cloud project.
-- Creates empty portal-owned tables. No public table or existing row is moved.
-- Run after create_workforce_portal_system.sql in the CTNP Systems SQL Editor.
begin;

create schema if not exists workforce_portal_system;
revoke all on schema workforce_portal_system from public, anon, authenticated;
grant usage on schema workforce_portal_system to service_role;

create table if not exists workforce_portal_system.work_schedules (
  schedule_id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete restrict,
  shift_start time without time zone not null,
  shift_end time without time zone not null,
  shift_type text,
  time_zone text not null default 'Asia/Manila',
  effective_from timestamptz not null default now(),
  effective_to timestamptz,
  is_active boolean not null default true,
  created_by_employee_id bigint references public.employees(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint work_schedules_different_times check (shift_start <> shift_end),
  constraint work_schedules_period check (effective_to is null or effective_to >= effective_from),
  constraint work_schedules_id_employee_unique unique (schedule_id, employee_id)
);
create unique index if not exists work_schedules_one_active_per_employee_idx
  on workforce_portal_system.work_schedules (employee_id) where is_active;
create index if not exists work_schedules_employee_period_idx
  on workforce_portal_system.work_schedules (employee_id, effective_from desc);

create table if not exists workforce_portal_system.work_shifts (
  shift_id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete restrict,
  schedule_id bigint,
  shift_date date not null,
  started_at timestamptz,
  ended_at timestamptz,
  status text not null default 'scheduled',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint work_shifts_status check (status in ('scheduled','active','completed','unclosed','cancelled')),
  constraint work_shifts_order check (ended_at is null or (started_at is not null and ended_at >= started_at)),
  constraint work_shifts_schedule_employee_fkey foreign key (schedule_id, employee_id)
    references workforce_portal_system.work_schedules(schedule_id, employee_id)
);
create index if not exists work_shifts_employee_date_idx
  on workforce_portal_system.work_shifts (employee_id, shift_date desc);
create unique index if not exists work_shifts_one_active_per_employee_idx
  on workforce_portal_system.work_shifts (employee_id) where status = 'active';

create table if not exists workforce_portal_system.shift_punches (
  punch_id bigint generated by default as identity primary key,
  shift_id bigint not null references workforce_portal_system.work_shifts(shift_id) on delete restrict,
  punch_type text not null,
  occurred_at timestamptz not null,
  source_log_id text unique,
  created_at timestamptz not null default now(),
  constraint shift_punches_type check (punch_type in (
    'Shift Start','Break 1 Start','Break 1 End','Start Lunch',
    'End Lunch','Break 2 Start','Break 2 End','Shift End'
  ))
);
create index if not exists shift_punches_shift_time_idx
  on workforce_portal_system.shift_punches (shift_id, occurred_at);

create table if not exists workforce_portal_system.task_time_entries (
  entry_id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete restrict,
  account_id bigint references public.accounts(account_id) on delete set null,
  shift_date date not null,
  duration_seconds integer not null,
  ticket_number text,
  tagging text,
  summary text not null,
  employee_name_snapshot text,
  account_code_snapshot text,
  source_ticket_number text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint task_time_entries_duration check (duration_seconds >= 0),
  constraint task_time_entries_summary check (length(btrim(summary)) > 0)
);
create index if not exists task_time_entries_employee_date_idx
  on workforce_portal_system.task_time_entries (employee_id, shift_date desc);
create index if not exists task_time_entries_account_date_idx
  on workforce_portal_system.task_time_entries (account_id, shift_date desc);
create index if not exists task_time_entries_ticket_idx
  on workforce_portal_system.task_time_entries (ticket_number);

create table if not exists workforce_portal_system.attendance_overrides (
  override_id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete restrict,
  attendance_date date not null,
  status text not null,
  note text,
  updated_by_employee_id bigint references public.employees(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint attendance_overrides_employee_date_unique unique (employee_id, attendance_date),
  constraint attendance_overrides_status_nonblank check (length(btrim(status)) > 0)
);
create index if not exists attendance_overrides_date_idx
  on workforce_portal_system.attendance_overrides (attendance_date desc);

create table if not exists workforce_portal_system.notifications (
  notification_id bigint generated by default as identity primary key,
  recipient_employee_id bigint not null references public.employees(id) on delete cascade,
  title text not null,
  description text not null,
  action_url text,
  read_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists portal_notifications_recipient_date_idx
  on workforce_portal_system.notifications (recipient_employee_id, created_at desc);
create index if not exists portal_notifications_unread_idx
  on workforce_portal_system.notifications (recipient_employee_id, created_at desc) where read_at is null;

create table if not exists workforce_portal_system.focus_state (
  employee_id bigint primary key references public.employees(id) on delete cascade,
  timer_mode text not null default 'focus',
  duration_minutes integer not null default 25,
  remaining_seconds integer not null default 1500,
  is_active boolean not null default false,
  started_at timestamptz,
  session_started_at timestamptz,
  session_token uuid,
  updated_at timestamptz not null default now(),
  constraint focus_state_mode check (timer_mode in ('focus','short_break','long_break')),
  constraint focus_state_duration check (duration_minutes between 1 and 240),
  constraint focus_state_remaining check (remaining_seconds between 0 and 86400)
);

create table if not exists workforce_portal_system.focus_sessions (
  focus_session_id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete cascade,
  session_token uuid not null unique,
  timer_mode text not null,
  duration_minutes integer not null,
  started_at timestamptz not null,
  ended_at timestamptz not null,
  completed_on date not null,
  constraint focus_sessions_order check (ended_at >= started_at),
  constraint focus_sessions_duration check (duration_minutes > 0)
);
create index if not exists focus_sessions_employee_day_idx
  on workforce_portal_system.focus_sessions (employee_id, completed_on desc);

create table if not exists workforce_portal_system.tasks (
  task_id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete cascade,
  title text not null,
  ticket_code text,
  priority text not null default 'MEDIUM',
  status text not null default 'todo',
  estimate text,
  category text not null default 'General',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint tasks_title_nonblank check (length(btrim(title)) > 0),
  constraint tasks_priority check (priority in ('HIGH','MEDIUM','LOW')),
  constraint tasks_status check (status in ('todo','inprogress','done'))
);
create index if not exists portal_tasks_employee_status_idx
  on workforce_portal_system.tasks (employee_id, status, created_at desc);

create table if not exists workforce_portal_system.notes (
  note_id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete cascade,
  note_type text not null,
  title text not null default 'Notes',
  content text not null default '',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint notes_type check (note_type in ('sticky','shift','mind_dump')),
  constraint notes_metadata_object check (jsonb_typeof(metadata) = 'object')
);
create index if not exists portal_notes_employee_type_idx
  on workforce_portal_system.notes (employee_id, note_type, created_at desc);

create table if not exists workforce_portal_system.routines (
  routine_id bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete cascade,
  name text not null,
  category text not null default 'general',
  duration_minutes integer not null,
  time_of_day text not null default 'Daily Routine',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint routines_name_nonblank check (length(btrim(name)) > 0),
  constraint routines_duration check (duration_minutes between 1 and 1440),
  constraint routines_id_employee_unique unique (routine_id, employee_id)
);
create index if not exists portal_routines_employee_active_idx
  on workforce_portal_system.routines (employee_id, is_active, created_at desc);

create table if not exists workforce_portal_system.routine_completions (
  completion_id bigint generated by default as identity primary key,
  routine_id bigint not null,
  employee_id bigint not null references public.employees(id) on delete cascade,
  completed_on date not null,
  created_at timestamptz not null default now(),
  constraint routine_completions_once_per_day unique (routine_id, completed_on),
  constraint routine_completions_owner_fkey foreign key (routine_id, employee_id)
    references workforce_portal_system.routines(routine_id, employee_id) on delete cascade
);
create index if not exists routine_completions_employee_day_idx
  on workforce_portal_system.routine_completions (employee_id, completed_on desc);

-- The app uses its own signed cookie and accesses Supabase only on the server.
-- Explicit statements let Studio recognize RLS in its pre-run safety scan.
alter table workforce_portal_system.work_schedules enable row level security;
alter table workforce_portal_system.work_shifts enable row level security;
alter table workforce_portal_system.shift_punches enable row level security;
alter table workforce_portal_system.task_time_entries enable row level security;
alter table workforce_portal_system.attendance_overrides enable row level security;
alter table workforce_portal_system.notifications enable row level security;
alter table workforce_portal_system.focus_state enable row level security;
alter table workforce_portal_system.focus_sessions enable row level security;
alter table workforce_portal_system.tasks enable row level security;
alter table workforce_portal_system.notes enable row level security;
alter table workforce_portal_system.routines enable row level security;
alter table workforce_portal_system.routine_completions enable row level security;

-- No direct client access; the server service role is authorized in API routes.
revoke all on workforce_portal_system.work_schedules from anon, authenticated;
revoke all on workforce_portal_system.work_shifts from anon, authenticated;
revoke all on workforce_portal_system.shift_punches from anon, authenticated;
revoke all on workforce_portal_system.task_time_entries from anon, authenticated;
revoke all on workforce_portal_system.attendance_overrides from anon, authenticated;
revoke all on workforce_portal_system.notifications from anon, authenticated;
revoke all on workforce_portal_system.focus_state from anon, authenticated;
revoke all on workforce_portal_system.focus_sessions from anon, authenticated;
revoke all on workforce_portal_system.tasks from anon, authenticated;
revoke all on workforce_portal_system.notes from anon, authenticated;
revoke all on workforce_portal_system.routines from anon, authenticated;
revoke all on workforce_portal_system.routine_completions from anon, authenticated;
grant select, insert, update, delete on workforce_portal_system.work_schedules to service_role;
grant select, insert, update, delete on workforce_portal_system.work_shifts to service_role;
grant select, insert, update, delete on workforce_portal_system.shift_punches to service_role;
grant select, insert, update, delete on workforce_portal_system.task_time_entries to service_role;
grant select, insert, update, delete on workforce_portal_system.attendance_overrides to service_role;
grant select, insert, update, delete on workforce_portal_system.notifications to service_role;
grant select, insert, update, delete on workforce_portal_system.focus_state to service_role;
grant select, insert, update, delete on workforce_portal_system.focus_sessions to service_role;
grant select, insert, update, delete on workforce_portal_system.tasks to service_role;
grant select, insert, update, delete on workforce_portal_system.notes to service_role;
grant select, insert, update, delete on workforce_portal_system.routines to service_role;
grant select, insert, update, delete on workforce_portal_system.routine_completions to service_role;

-- Identity sequences used by these new tables. focus_state uses employee_id
-- as its key and has no identity sequence.
grant usage, select on sequence
  workforce_portal_system.work_schedules_schedule_id_seq,
  workforce_portal_system.work_shifts_shift_id_seq,
  workforce_portal_system.shift_punches_punch_id_seq,
  workforce_portal_system.task_time_entries_entry_id_seq,
  workforce_portal_system.attendance_overrides_override_id_seq,
  workforce_portal_system.notifications_notification_id_seq,
  workforce_portal_system.focus_sessions_focus_session_id_seq,
  workforce_portal_system.tasks_task_id_seq,
  workforce_portal_system.notes_note_id_seq,
  workforce_portal_system.routines_routine_id_seq,
  workforce_portal_system.routine_completions_completion_id_seq
  to service_role;

commit;
