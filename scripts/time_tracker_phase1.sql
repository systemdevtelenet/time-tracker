-- Add stable identity to the existing task-entry table without interrupting old app writes.
-- Target: self-hosted CTNP Systems PostgreSQL database, NOT the separate cloud project.
-- Run in a transaction. An ambiguous historical owner aborts the transaction.
begin;

alter table public.phone_time_tracker
  add column if not exists entry_id bigint generated by default as identity,
  add column if not exists employee_id bigint;

-- Historical rows must each match exactly one employee by their display name.
-- Current read-only audit found four unambiguous matches; re-check at run time.
do $$
begin
  if exists (
    select 1
    from public.phone_time_tracker p
    where p.employee_id is null
      and (select count(*) from public.employees e
           where lower(btrim(e.employee_name)) = lower(btrim(p.name))) <> 1
  ) then
    raise exception 'Task-entry owner backfill stopped: a name has zero or multiple employee matches';
  end if;
end $$;

update public.phone_time_tracker p
set employee_id = e.id
from public.employees e
where p.employee_id is null
  and lower(btrim(e.employee_name)) = lower(btrim(p.name));

-- Use the new column as the primary key when the legacy table has none.
-- If another primary key already exists, keep it and add a unique entry ID.
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.phone_time_tracker'::regclass and contype = 'p'
  ) then
    alter table public.phone_time_tracker
      add constraint phone_time_tracker_pkey primary key (entry_id);
  else
    create unique index if not exists phone_time_tracker_entry_id_uidx
      on public.phone_time_tracker (entry_id);
  end if;
end $$;

-- The referenced key is employees.id (bigint). The FK is safe for the current
-- four rows but remains nullable so an old app deployment can keep writing.
do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.phone_time_tracker'::regclass
      and conname = 'phone_time_tracker_employee_id_fkey'
  ) then
    alter table public.phone_time_tracker
      add constraint phone_time_tracker_employee_id_fkey
      foreign key (employee_id) references public.employees(id) on delete restrict;
  end if;
end $$;

create index if not exists phone_time_tracker_employee_date_idx
  on public.phone_time_tracker (employee_id, date_of_shift desc);
create index if not exists phone_time_tracker_ticket_idx
  on public.phone_time_tracker (ticket_number);

alter table public.phone_time_tracker enable row level security;
revoke all on public.phone_time_tracker from anon, authenticated;
grant select, insert, update, delete on public.phone_time_tracker to service_role;
grant usage, select on sequence public.phone_time_tracker_entry_id_seq to service_role;

notify pgrst, 'reload schema';
commit;
